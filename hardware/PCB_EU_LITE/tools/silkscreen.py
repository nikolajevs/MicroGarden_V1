# These devices have an even number of external leads.  Exposed pads are
# thermal pads rather than a "leg", so U101/U201/U501 retain a pin-1 cue.
IC_PIN1_REFS = {'U101', 'U102', 'U201', 'U202', 'U301', 'U401', 'U501'}


def ident(name):
    return str(uuid.uuid5(NS, name))


def side_of(fp):
    return 'B' if fp.IsFlipped() else 'F'


def from_box(value):
    return (p.ToMM(value.GetLeft()), p.ToMM(value.GetTop()),
            p.ToMM(value.GetRight()), p.ToMM(value.GetBottom()))


def item_box(item):
    return from_box(item.GetBoundingBox())


def expand(area, margin):
    return (area[0] - margin, area[1] - margin,
            area[2] + margin, area[3] + margin)


def intersects(a, b):
    return a[0] < b[2] and a[2] > b[0] and a[1] < b[3] and a[3] > b[1]


def box_distance(a, b):
    dx = max(a[0] - b[2], b[0] - a[2], 0)
    dy = max(a[1] - b[3], b[1] - a[3], 0)
    return math.hypot(dx, dy)


def point_box_distance(point, area):
    x, y = point
    dx = max(area[0] - x, x - area[2], 0)
    dy = max(area[1] - y, y - area[3], 0)
    return math.hypot(dx, dy)


def inside_board(area):
    return (area[0] >= BOARD_MARGIN_MM and area[1] >= BOARD_MARGIN_MM and
            area[2] <= 100 - BOARD_MARGIN_MM and area[3] <= 100 - BOARD_MARGIN_MM)


def numbered_pads(fp):
    return {str(pad.GetNumber()) for pad in fp.Pads() if str(pad.GetNumber())}


def has_even_pin_count(fp):
    return len(numbered_pads(fp)) % 2 == 0


def without_generated(text):
    """Remove exactly the managed group plus the superseded LED legends."""
    edits = []
    members = set()
    for start, end in spans(text, 'group'):
        node = parse(text[start:end])
        if node[1] == GROUP:
            members.update(child(node, 'members')[1:])
            edits.append((start, end))
    for tag in ('gr_text', 'gr_circle'):
        for start, end in spans(text, tag):
            node = parse(text[start:end])
            marker = child(node, 'uuid')[1]
            if marker in members or marker in LEGACY_LED_LABELS:
                edits.append((start, end))
                members.discard(marker)
    if members:
        raise RuntimeError('Managed silkscreen group contains unsupported members')
    for start, end in sorted(edits, reverse=True):
        text = text[:start] + text[end:]
    text = re.sub(r'(?m)^[ \t]+$', '', text)
    return text[:text.rfind(')')].rstrip() + '\n)\n'


class Layout:
    """Conservative, bounding-box-only silk placement on the two board faces."""

    def __init__(self, board):
        self.board = board
        self.fps = {fp.GetReference(): fp for fp in board.GetFootprints()}
        self.bodies = {ref: from_box(fp.GetBoundingBox(False)) for ref, fp in self.fps.items()}
        self.bodies_by_side = {
            side: [(ref, body) for ref, body in self.bodies.items()
                   if side_of(self.fps[ref]) == side]
            for side in ('F', 'B')
        }
        self.obstacles = {'F': [], 'B': []}  # (box, ref, kind)
        self.placed = {'F': [], 'B': []}
        self.text_box_cache = {}
        self.labels = []
        self.skipped = []
        self.native_marks = []
        for ref, fp in self.fps.items():
            face = side_of(fp)
            self.obstruct(face, expand(self.bodies[ref], .12), ref, 'body')
            if ref.startswith('H'):
                self.obstruct('B', expand(self.bodies[ref], .12), ref, 'body')
            for pad in fp.Pads():
                area = expand(item_box(pad), SILK_CLEARANCE_MM)
                if pad.IsOnLayer(p.F_Cu):
                    self.obstruct('F', area, ref, 'pad')
                if pad.IsOnLayer(p.B_Cu) or pad.GetDrillSizeX() > 0:
                    self.obstruct('B', area, ref, 'pad')
                if pad.GetDrillSizeX() > 0:
                    self.obstruct('F', area, ref, 'pad')
            for graphic in [*fp.GraphicalItems(), *fp.GetFields()]:
                if hasattr(graphic, 'IsVisible') and not graphic.IsVisible():
                    continue
                if graphic.GetLayer() == p.F_SilkS:
                    self.obstruct('F', expand(item_box(graphic), SILK_CLEARANCE_MM), ref, 'silk')
                elif graphic.GetLayer() == p.B_SilkS:
                    self.obstruct('B', expand(item_box(graphic), SILK_CLEARANCE_MM), ref, 'silk')
        for graphic in board.GetDrawings():
            if graphic.GetLayer() == p.F_SilkS:
                self.obstruct('F', expand(item_box(graphic), SILK_CLEARANCE_MM), None, 'silk')
            elif graphic.GetLayer() == p.B_SilkS:
                self.obstruct('B', expand(item_box(graphic), SILK_CLEARANCE_MM), None, 'silk')
        for track in board.GetTracks():
            if track.GetClass() == 'PCB_VIA':
                area = expand(item_box(track), SILK_CLEARANCE_MM)
                self.obstruct('F', area, None, 'via')
                self.obstruct('B', area, None, 'via')

    def obstruct(self, side, area, ref, kind):
        self.obstacles[side].append((area, ref, kind))

    def blocked(self, side, area, ref=None, allow_own_body=False):
        for obstacle, owner, kind in self.obstacles[side]:
            if not intersects(area, obstacle):
                continue
            if allow_own_body and owner == ref and kind == 'body':
                continue
            return True
        return any(intersects(area, prior) for prior in self.placed[side])

    def text_box(self, text, side, size, x, y, rotation):
        key = (text, side, size, rotation)
        base = self.text_box_cache.get(key)
        if base is None:
            item = p.PCB_TEXT(self.board)
            item.SetText(text)
            item.SetLayer(p.B_SilkS if side == 'B' else p.F_SilkS)
            item.SetMirrored(side == 'B')
            item.SetTextAngle(p.EDA_ANGLE(rotation, p.DEGREES_T))
            item.SetTextSize(p.VECTOR2I(p.FromMM(size), p.FromMM(size)))
            item.SetTextThickness(p.FromMM(TEXT_STROKE_MM))
            item.SetPosition(p.VECTOR2I(0, 0))
            base = item_box(item)
            self.text_box_cache[key] = base
        return (base[0] + x, base[1] + y, base[2] + x, base[3] + y)

    def add(self, name, text, ref, side, size=TEXT_MM, anchor=None,
            max_distance=4, other_pins=(), rotation=0, allow_own_body=False,
            fine=False):
        body = self.bodies[ref]
        trial = self.text_box(text, side, size, 0, 0, rotation)
        half_w = (trial[2] - trial[0]) / 2
        half_h = (trial[3] - trial[1]) / 2
        x0, y0, x1, y1 = body
        ax, ay = anchor or ((x0 + x1) / 2, (y0 + y1) / 2)
        candidates = []
        for distance in (.3, .7, 1.1, 1.5, 2.0, 2.5, 3.0):
            for delta in (0, -.5, .5, -1, 1, -1.5, 1.5, -2, 2):
                candidates.extend(((ax + delta, y0 - half_h - distance),
                                   (ax + delta, y1 + half_h + distance),
                                   (x0 - half_w - distance, ay + delta),
                                   (x1 + half_w + distance, ay + delta)))
        if anchor:
            for distance in (1.5, 1.8, 2.2, 2.6, 3.0, 3.5, 4.0):
                candidates.extend(((ax, ay - distance - half_h),
                                   (ax, ay + distance + half_h),
                                   (ax - distance - half_w, ay),
                                   (ax + distance + half_w, ay)))
        if fine:
            # The coarse offsets miss narrow but usable gaps. Fit the actual
            # text bounds against nearby obstacle/label edges; keep the same
            # collision and nearest-component rules as the ordinary pass.
            region = expand(body, 4)
            nearby = [area for area, _, _ in self.obstacles[side]
                      if intersects(region, area)]
            nearby += [area for area in self.placed[side]
                       if intersects(region, area)]
            xs, ys = {ax}, {ay}
            for area in [expand(body, .12), *nearby]:
                xs.update((area[0] - trial[2] - .02,
                           area[2] - trial[0] + .02))
                ys.update((area[1] - trial[3] - .02,
                           area[3] - trial[1] + .02))
            xs = sorted(x for x in xs if x0 - 3 <= x <= x1 + 3)
            ys = sorted(y for y in ys if y0 - 3 <= y <= y1 + 3)
            candidates.extend((x, y) for x in xs for y in ys
                              if point_box_distance((x, y), body) <= 3)
        candidates = sorted(set(candidates), key=lambda point: math.dist(point, (ax, ay)))
        # Only nearby components can make a reference ambiguous. Derive the
        # search radius from all candidate centres rather than a fixed guess.
        reach = max((point_box_distance(point, body) for point in candidates), default=0)
        vicinity = expand(body, 2 * reach + .1)
        neighbors = [other for other_ref, other in self.bodies_by_side[side]
                     if other_ref != ref and intersects(vicinity, other)]
        for x, y in candidates:
            area = self.text_box(text, side, size, x, y, rotation)
            if not inside_board(area):
                continue
            if anchor and math.dist((x, y), anchor) > max_distance:
                continue
            if ref == 'U202' and not anchor:
                position = self.fps[ref].GetPosition()
                if abs(x - p.ToMM(position.x)) > 12 or abs(y - p.ToMM(position.y)) > 18:
                    continue
            if anchor and any(math.dist((x, y), other) < math.dist((x, y), anchor) + .25 for other in other_pins):
                continue
            if not anchor:
                own_distance = point_box_distance((x, y), body)
                if any(point_box_distance((x, y), other) + .05 < own_distance
                       for other in neighbors):
                    continue
            if self.blocked(side, area, ref, allow_own_body):
                continue
            self.placed[side].append(expand(area, LABEL_CLEARANCE_MM))
            entry = dict(name=name, kind='text', text=text, ref=ref, side=side,
                         at=[round(x, 4), round(y, 4)], rotation_deg=rotation,
                         size_mm=size, uuid=ident(name))
            self.labels.append(entry)
            return entry
        return None

    def pin(self, ref, pin, text, net, faces=None, size=TEXT_MM,
            record_skip=True):
        fp = self.fps[ref]
        pads = [pad for pad in fp.Pads() if str(pad.GetNumber()) == str(pin)]
        if net is None:
            valid = pads and all(not pad.GetNetname() or pad.GetNetname().startswith('unconnected-') for pad in pads)
        else:
            valid = pads and all(pad.GetNetname() == net for pad in pads)
        if not valid:
            raise RuntimeError(f'{ref}.{pin}: silk legend disagrees with PCB net {net!r}')
        position = pads[0].GetPosition()
        anchor = (p.ToMM(position.x), p.ToMM(position.y))
        other_pins = [(p.ToMM(pad.GetPosition().x), p.ToMM(pad.GetPosition().y))
                      for pad in fp.Pads() if pad.GetNumber() and str(pad.GetNumber()) != str(pin)]
        if faces is None:
            faces = ('F', 'B') if not (fp.GetAttributes() & p.FP_SMD) else (side_of(fp),)
        placed = []
        for side in faces:
            item = self.add(f'{ref}/pin/{pin}/{side}', text, ref, side,
                            anchor=anchor, max_distance=6, other_pins=other_pins,
                            allow_own_body=True, size=size)
            if item:
                item.update(pin=str(pin), net=net if net is not None else 'unconnected')
                placed.append(item)
        if not placed and record_skip:
            self.skipped.append(dict(ref=ref, pin=str(pin), text=text,
                                     reason='no clear space within 6 mm of pin'))
        return placed

    def native_pin1(self, ref, pin='1'):
        fp = self.fps[ref]
        pads = [pad for pad in fp.Pads() if str(pad.GetNumber()) == str(pin)]
        if not pads:
            return False
        target = item_box(pads[0])
        layer = p.B_SilkS if fp.IsFlipped() else p.F_SilkS
        for graphic in fp.GraphicalItems():
            if graphic.GetLayer() != layer or not isinstance(graphic, p.PCB_SHAPE):
                continue
            try:
                solid = graphic.IsSolidFill()
            except AttributeError:
                solid = False
            if solid and box_distance(item_box(graphic), target) < 2.5:
                return True
        return False

    def dot(self, ref, pin, net):
        fp = self.fps[ref]
        pads = [pad for pad in fp.Pads() if str(pad.GetNumber()) == str(pin)]
        if not pads or any(pad.GetNetname() != net for pad in pads):
            raise RuntimeError(f'{ref}.{pin}: pin-1 dot disagrees with PCB net {net!r}')
        side = side_of(fp)
        target = item_box(pads[0])
        centre = ((target[0] + target[2]) / 2, (target[1] + target[3]) / 2)
        other = [item_box(pad) for pad in fp.Pads() if pad.GetNumber() and str(pad.GetNumber()) != str(pin)]
        diameter = .5
        candidates = []
        for distance in (0, .1, .2, .3, .4, .5, .6, .8, 1.0):
            for angle in range(0, 360, 15):
                x = centre[0] + distance * math.cos(math.radians(angle))
                y = centre[1] + distance * math.sin(math.radians(angle))
                candidates.append((distance, angle, x, y))
        for _, _, x, y in candidates:
            area = (x - diameter / 2, y - diameter / 2, x + diameter / 2, y + diameter / 2)
            if not inside_board(area) or self.blocked(side, expand(area, .1), ref, allow_own_body=True):
                continue
            if any(point_box_distance((x, y), candidate) < point_box_distance((x, y), target) + .05 for candidate in other):
                continue
            self.placed[side].append(expand(area, LABEL_CLEARANCE_MM))
            entry = dict(name=f'{ref}/pin/{pin}/dot/{side}', kind='dot', ref=ref,
                         side=side, pin=str(pin), net=net, at=[round(x, 4), round(y, 4)],
                         diameter_mm=diameter, uuid=ident(f'{ref}/pin/{pin}/dot/{side}'))
            self.labels.append(entry)
            return entry
        self.skipped.append(dict(ref=ref, pin=str(pin), reason='no unambiguous space for a pin-1 dot'))
        return None


def render(labels):
    blocks = []
    for label in labels:
        x, y = label['at']
        if label['kind'] == 'dot':
            radius = round(label['diameter_mm'] / 2 - TEXT_STROKE_MM / 2, 4)
            blocks.append(f'\t(gr_circle (center {x} {y}) (end {round(x + radius, 4)} {y}) '
                          f'(stroke (width {TEXT_STROKE_MM}) (type default)) (fill yes) '
                          f'(layer "{label["side"]}.SilkS") (uuid "{label["uuid"]}"))')
            continue
        mirror = ' (justify mirror)' if label['side'] == 'B' else ''
        blocks.append(f'\t(gr_text {json.dumps(label["text"])} (at {x} {y} {label["rotation_deg"]}) '
                      f'(layer "{label["side"]}.SilkS") (uuid "{label["uuid"]}") '
                      f'(effects (font (size {label["size_mm"]} {label["size_mm"]}) '
                      f'(thickness {TEXT_STROKE_MM})){mirror}))')
    members = ' '.join(f'"{label["uuid"]}"' for label in labels)
    blocks.append(f'\t(group "{GROUP}" (uuid "{ident(GROUP)}") (members {members}))')
    return '\n'.join(blocks) + '\n'


def connector_check(parts, ref, pin, expected):
    schematic = parts[ref]['nets'].get(str(pin))
    if expected is not None and schematic != expected:
        raise RuntimeError(f'{ref}.{pin}: design.json net {schematic!r}, expected {expected!r}')
    if expected is None and schematic is not None:
        raise RuntimeError(f'{ref}.{pin}: expected an unconnected pin, got {schematic!r}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--board', type=Path, default=HERE / 'PCB_EU_LITE.kicad_pcb')
    parser.add_argument('--check', action='store_true', help='Require existing managed silk to match regeneration')
    parser.add_argument('--output', type=Path, default=HERE / 'review' / 'silkscreen.json')
    args = parser.parse_args()
    if not p.Version().startswith('10.'):
        parser.error('KiCad 10 pcbnew is required; never downgrade the PCB file')

    original = args.board.read_text(encoding='utf-8')
    base = without_generated(original)
    with tempfile.TemporaryDirectory(prefix='eu-lite-silkscreen-') as temp:
        staged = Path(temp) / args.board.name
        staged.write_text(base, encoding='utf-8')
        layout = Layout(p.LoadBoard(str(staged)))
    parts = {part['ref']: part for part in json.loads((HERE / 'design.json').read_text(encoding='utf-8'))['parts']}
    # Keep this explicit in the review artifact: components with an odd count
    # of real pads receive a reference, but never a generated polarity/pin-1
    # cue. Mounting holes are not electrical components and are excluded.
    odd_polarity_omitted = [
        ref for ref, fp in layout.fps.items()
        if (not ref.startswith('H') and ref not in IC_PIN1_REFS
            and not has_even_pin_count(fp))
    ]
    # First preserve space for the requested component references and their
    # polarity. Connector titles are intentionally omitted: their J-number is
    # a lower assembly priority than ordinary component positions.
    for ref, pins in POLARITY_PINS.items():
        fp = layout.fps[ref]
        if not has_even_pin_count(fp):
            continue
        for pin, net, text in pins:
            if parts[ref]['nets'].get(str(pin)) != net:
                raise RuntimeError(f'{ref}.{pin}: design.json polarity net changed')
            placed = layout.pin(ref, pin, text, net, faces=(side_of(fp),),
                                record_skip=False)
            if not placed:
                layout.pin(ref, pin, text, net, faces=(side_of(fp),),
                           size=COMPACT_TEXT_MM)

    for ref in sorted(IC_PIN1_REFS):
        fp = layout.fps[ref]
        if layout.native_pin1(ref):
            layout.native_marks.append(ref)
            continue
        layout.dot(ref, '1', parts[ref]['nets']['1'])

    # Dense resistor banks have the fewest usable nearby gaps, so reserve
    # their labels first. Connectors deliberately remain last.
    priorities = lambda ref: (
        ref.startswith('J'),
        0 if ref.startswith('R') else 1 if ref.startswith(('U', 'Q')) else 2,
        ref,
    )
    for ref in sorted(layout.fps, key=priorities):
        if ref.startswith(('H', 'J')):
            continue
        fp = layout.fps[ref]
        side = side_of(fp)
        item = layout.add(f'{ref}/reference/{side}', ref, ref, side)
        # Keep references on the component side. A vertical placement makes
        # dense positions easier to read without turning the bottom into a
        # mirrored index for top-side components.
        if not item:
            item = layout.add(f'{ref}/reference/{side}/vertical', ref, ref, side,
                              rotation=90)
        # Keep compact text on the component side too. It is preferable to a
        # full-size label on the reverse side when the board is assembled.
        if not item:
            item = layout.add(f'{ref}/reference/{side}/compact', ref, ref, side,
                              size=COMPACT_TEXT_MM)
        if not item:
            item = layout.add(f'{ref}/reference/{side}/compact-vertical', ref,
                              ref, side, size=COMPACT_TEXT_MM, rotation=90)
        if not item:
            layout.skipped.append(dict(
                ref=ref,
                reason='no clear space on the component side for readable reference',
            ))

    # Pin legends for connectors are still useful, especially +/- on power
    # terminals, but go last and only on their component side so they cannot
    # displace ordinary component positions.
    for ref, (_, pins) in CONNECTORS.items():
        fp = layout.fps[ref]
        if not has_even_pin_count(fp):
            continue
        for pin, net, text in pins:
            connector_check(parts, ref, pin, net)
            layout.pin(ref, pin, text, net, faces=(side_of(fp),))

    # Connector reference designators are a final best-effort addition.
    for ref in sorted(ref for ref in layout.fps if ref.startswith('J')):
        fp = layout.fps[ref]
        side = side_of(fp)
        item = layout.add(f'{ref}/reference/{side}', ref, ref, side)
        # These labels are explicit position designators, not pin legends:
        # prefer an outside vertical placement on the visible component side.
        if not item:
            item = layout.add(f'{ref}/reference/{side}/vertical', ref, ref, side,
                              rotation=90)
        if not item:
            layout.skipped.append(dict(
                ref=ref,
                reason='no clear space on the component side for low-priority connector reference',
            ))

    # Preserve the established legends and references, then recover omitted
    # positions from smaller gaps using exact obstacle-edge candidates.
    recovered = []
    for omission in sorted(list(layout.skipped), key=lambda item: priorities(item['ref'])):
        if 'reference' not in omission['reason']:
            continue
        ref = omission['ref']
        side = side_of(layout.fps[ref])
        variants = [(TEXT_MM, 0, ''), (TEXT_MM, 90, '/vertical')]
        if not ref.startswith('J'):
            variants += [(COMPACT_TEXT_MM, 0, '/compact'),
                         (COMPACT_TEXT_MM, 90, '/compact-vertical')]
        for size, rotation, suffix in variants:
            item = layout.add(f'{ref}/reference/{side}{suffix}', ref, ref, side,
                              size=size, rotation=rotation, fine=True)
            if item:
                layout.skipped.remove(omission)
                recovered.append(ref)
                break

    reference_labels = [
        label for label in layout.labels if '/reference/' in label['name']
    ]
    cross_side_references = sorted(
        label['ref'] for label in reference_labels
        if label['side'] != side_of(layout.fps[label['ref']])
    )
    if cross_side_references:
        raise RuntimeError(
            'Reference designators must remain on the component side: '
            + ', '.join(cross_side_references)
        )

    updated = base[:base.rfind(')')] + render(layout.labels) + ')\n'
    if parse(without_generated(updated)) != parse(base):
        raise RuntimeError('Non-silkscreen PCB data changed')
    if args.check:
        old = {child(node, 'uuid')[1]: node for tag in ('gr_text', 'gr_circle') for node in children(parse(original), tag)}
        new = {child(node, 'uuid')[1]: node for tag in ('gr_text', 'gr_circle') for node in children(parse(updated), tag)}
        if old != new:
            raise RuntimeError('Managed silk is stale: regenerate with tools/silkscreen.py')
    else:
        args.board.write_text(updated, encoding='utf-8', newline='\n')

    args.output.parent.mkdir(parents=True, exist_ok=True)
    report = dict(
        pcbnew_version=p.Version(),
        scope='generated assembly silk only; copper, pads, routes, zones and Fab fields are unchanged',
        standard_text_mm=TEXT_MM,
        compact_text_mm=COMPACT_TEXT_MM,
        stroke_mm=TEXT_STROKE_MM,
        generated_labels=len(layout.labels),
        labels_by_face=dict(Counter(label['side'] for label in layout.labels)),
        references_placed=len(reference_labels),
        references_recovered_by_edge_search=recovered,
        references_by_face=dict(Counter(label['side'] for label in reference_labels)),
        cross_side_references=cross_side_references,
        compact_references=sum('/compact' in label['name'] for label in layout.labels),
        vertical_references=sum(
            label['name'].endswith('vertical') for label in layout.labels
        ),
        component_polarity_labels=sum(
            label['ref'] in POLARITY_PINS and '/pin/' in label['name']
            and label['kind'] == 'text' for label in layout.labels),
        connector_pin_labels=sum(
            label['ref'] in CONNECTORS and '/pin/' in label['name']
            and label['kind'] == 'text' for label in layout.labels),
        capacitor_plus_omitted_in_local_footprints=sorted(CAPACITOR_PLUS_OMITTED_REFS),
        polarity_covered_parts=sorted(POLARITY_PINS),
        ic_pin1_dots=sum(label['kind'] == 'dot' for label in layout.labels),
        ic_native_pin1_marks=layout.native_marks,
        polarity_omitted_for_odd_pin_parts=sorted(set(odd_polarity_omitted)),
        native_footprint_marks='preserved; generated polarity/pin-1 marks are suppressed for odd-pin parts',
        labels=layout.labels,
        omitted=layout.skipped,
        base_pcb_sha256=hashlib.sha256(base.encode()).hexdigest(),
        generated_pcb_sha256=hashlib.sha256(updated.encode()).hexdigest(),
    )
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'PASS | EU-LITE silkscreen | {len(layout.labels)} labels; '
          f'{report["references_placed"]} references; {len(layout.skipped)} omitted; '
          f'{len(report["polarity_omitted_for_odd_pin_parts"])} odd-pin parts without generated polarity')


if __name__ == '__main__':
    main()
