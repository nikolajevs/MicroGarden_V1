#!/usr/bin/env python3
"""Generate collision-aware EU-LITE assembly silk after routing.

The generator adds readable references and polarity labels without changing
copper, footprint geometry or the Fab reference fields. It uses only KiCad
bounding boxes, so it works with the installed KiCad Python runtime without a
separate Shapely package. All generated graphics are kept in one group and can
be regenerated byte-for-byte.

Polarity is deliberately generated only for components with an even physical
pin count.  Three-pin / five-pin transistors and one-pin test points therefore
get a reference but no extra orientation mark, as requested by the owner.
SPDX-License-Identifier: MIT
"""
